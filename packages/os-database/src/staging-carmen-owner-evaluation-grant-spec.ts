const FORBIDDEN_TECHNICAL_SHORTCUTS = ['system.admin', 'integration.admin'] as const;

export function assertCarmenOwnerEvaluationGrantListSafe(
  scopes: readonly string[],
): void {
  for (const banned of FORBIDDEN_TECHNICAL_SHORTCUTS) {
    if (scopes.includes(banned)) {
      throw new Error(`OWNER_EVAL_FORBIDDEN_SCOPE:${banned}`);
    }
  }
  if (!scopes.includes(FINANCE_OPERATIONAL_RECORD_SCOPE)) {
    throw new Error('OWNER_EVAL_MISSING_FINANCE_SCOPE');
  }
}
